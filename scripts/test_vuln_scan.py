RUNTIME_EXPORT = """\
# This file was autogenerated by uv via the following command:
#    uv export --no-dev
annotated-types==0.8.0
    # via pydantic
pydantic==2.14.0
    # via flightdeck-sensor
"""


def ignore_toml(
    ident: str, package: str, ecosystem: str = "npm", expires: str = "2027-01-31", **extra: str
) -> str:
    lines = [
        "[[ignore]]",
        f'id = "{ident}"',
        f'ecosystem = "{ecosystem}"',
        f'package = "{package}"',
        'reason = "no fixed release"',
    ]
    if expires:
        lines.append(f"expires = {expires}")
    lines += [f"{k} = {v}" for k, v in extra.items()]
    return "\n".join(lines) + "\n"


def write_ignores(text: str) -> Path:
    handle = tempfile.NamedTemporaryFile("w", suffix=".toml", delete=False)
    handle.write(text)
    handle.close()
    return Path(handle.name)


def completed(
    stdout: str = "", stderr: str = "", code: int = 0
) -> subprocess.CompletedProcess[str]:
    return subprocess.CompletedProcess(["x"], code, stdout, stderr)


class LoadIgnoresTest(unittest.TestCase):
    def test_missing_file_means_no_ignores(self) -> None:
        self.assertEqual(vuln_scan.load_ignores(Path("/nonexistent/x.toml")), [])

    def test_shipped_file_is_valid(self) -> None:
        vuln_scan.load_ignores(vuln_scan.IGNORE_FILE)

    def test_reads_entries(self) -> None:
        (entry,) = vuln_scan.load_ignores(write_ignores(ignore_toml(HIGH["ghsa"], "lodash")))
        self.assertEqual(entry.id, HIGH["ghsa"])
        self.assertEqual(entry.reason, "no fixed release")
        self.assertEqual(entry.expires, datetime.date(2027, 1, 31))

    def test_rejects_entry_without_reason(self) -> None:
        for reason_line in ("", 'reason = ""\n', 'reason = "   "\n'):
            path = write_ignores(
                '[[ignore]]\nid = "X"\necosystem = "npm"\npackage = "p"\n'
                f"expires = 2027-01-01\n{reason_line}"
            )
            with self.assertRaisesRegex(vuln_scan.ScanError, "reason"):
                vuln_scan.load_ignores(path)

    def test_requires_expires_as_a_toml_date(self) -> None:
        for expires in ("", '"2027-01-31"', "2027-01-31T00:00:00"):
            path = write_ignores(ignore_toml("X", "p", expires=expires))
            with self.assertRaisesRegex(vuln_scan.ScanError, "expires"):
                vuln_scan.load_ignores(path)

    def test_rejects_unknown_ecosystem_and_keys(self) -> None:
        with self.assertRaisesRegex(vuln_scan.ScanError, "ecosystem"):
            vuln_scan.load_ignores(write_ignores(ignore_toml("X", "p", ecosystem="cargo")))
        with self.assertRaisesRegex(vuln_scan.ScanError, "unknown keys"):
            vuln_scan.load_ignores(write_ignores(ignore_toml("X", "p", until='"x"')))

    def test_rejects_malformed_toml(self) -> None:
        with self.assertRaises(vuln_scan.ScanError):
            vuln_scan.load_ignores(write_ignores("[[ignore]\n"))


class ParseTest(unittest.TestCase):
    def test_npm_one_finding_per_advisory(self) -> None:
        findings = vuln_scan.parse_npm_audit(npm_report(HIGH, MODERATE))
        self.assertEqual(
            [(f.package, f.id, f.severity) for f in findings],
            [("lodash", HIGH["ghsa"], "high"), ("minimatch", MODERATE["ghsa"], "moderate")],
        )

    def test_npm_error_shape_reports_message_and_stderr(self) -> None:
        report = {"message": "request to registry.npmjs.org failed", "error": {}}
        with self.assertRaisesRegex(vuln_scan.ScanError, "registry.npmjs.org failed") as ctx:
            vuln_scan.parse_npm_audit(report, "npm error code ENOTFOUND\n")
        self.assertIn("ENOTFOUND", str(ctx.exception))

    def test_pip_findings_dedupe_normalize_and_skips(self) -> None:
        report = {
            "dependencies": [
                {"name": "Pydantic", "version": "1.10.0", "vulns": [PYDANTIC_VULN]},
                {"name": "pydantic", "version": "1.10.0", "vulns": [PYDANTIC_VULN]},
                {"name": "local-pkg", "skip_reason": "not on PyPI"},
            ]
        }
        result = vuln_scan.parse_pip_audit(report)
        self.assertEqual(len(result.findings), 1)
        self.assertEqual(result.findings[0].package, "pydantic")
        self.assertEqual(result.audited, {("pydantic", "1.10.0")})
        self.assertEqual(result.skipped, ["local-pkg: not on PyPI"])

    def test_requirements_drop_markers_and_comments(self) -> None:
        pins, unpinned = vuln_scan.parse_requirements(
            RUNTIME_EXPORT
            + "jinja2==3.1.2 ; sys_platform == 'win32'\n"
            + "Typing_Extensions==4.16.0 ; python_full_version >= '3.14'\n"
            + "somepkg @ git+https://example.com/somepkg\n"
        )
        self.assertEqual(
            pins,
            [
                ("annotated-types", "0.8.0"),
                ("jinja2", "3.1.2"),
                ("pydantic", "2.14.0"),
                ("typing-extensions", "4.16.0"),
            ],
        )
        self.assertEqual(unpinned, ["somepkg @ git+https://example.com/somepkg"])

    def test_split_pins_one_version_per_package_per_file(self) -> None:
        files = vuln_scan.split_pins(
            [("deprecated", "1.3.1"), ("deprecated", "3.0.0"), ("pydantic", "2.14.0")]
        )
        self.assertEqual(
            files,
            [[("deprecated", "1.3.1"), ("pydantic", "2.14.0")], [("deprecated", "3.0.0")]],
        )


class IgnoreMatchTest(unittest.TestCase):
    def finding(self) -> vuln_scan.Finding:
        report = {
            "dependencies": [{"name": "zope.interface", "version": "1", "vulns": [PYDANTIC_VULN]}]
        }
        (finding,) = vuln_scan.parse_pip_audit(report).findings
        return finding

    def entry(self, ident: str, eco: str, package: str) -> vuln_scan.IgnoreEntry:
        return vuln_scan.IgnoreEntry(ident, eco, package, "r", datetime.date(2027, 1, 1))

    def test_matches_alias_and_pep503_name(self) -> None:
        entry = self.entry("CVE-2024-3772", "pypi", "Zope_Interface")
        self.assertIs(vuln_scan.is_ignored(self.finding(), [entry]), entry)

    def test_wrong_package_or_ecosystem_does_not_match(self) -> None:
        entries = [
            self.entry("CVE-2024-3772", "pypi", "other"),
            self.entry("CVE-2024-3772", "npm", "zope.interface"),
        ]
        self.assertIsNone(vuln_scan.is_ignored(self.finding(), entries))


class UtcTodayTest(unittest.TestCase):
    def test_uses_the_utc_date(self) -> None:
        class Clock(datetime.datetime):
            # 23:30 UTC on 15 June 2030; any non-UTC reading claims the
            # 16th, and the real clock is years away, so the test fails
            # unless the scanner asks this clock for UTC explicitly.
            @classmethod
            def now(cls, tz: datetime.tzinfo | None = None) -> Clock:
                day = 15 if tz is datetime.UTC else 16
                return cls(2030, 6, day, 23, 30, tzinfo=tz)

        with mock.patch("datetime.datetime", Clock):
            self.assertEqual(vuln_scan.utc_today(), datetime.date(2030, 6, 15))


