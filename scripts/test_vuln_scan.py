class ScanTest(unittest.TestCase):
    """Runs ``main`` with the external commands replaced."""

    def setUp(self) -> None:
        self.dashboard_all = npm_report()
        self.plugin_lock = False
        self.plugin_prod = npm_report()
        self.plugin_all = npm_report()
        self.runtime_export = RUNTIME_EXPORT
        self.full_export = RUNTIME_EXPORT
        # (name, version) -> vulns pip-audit reports for that pin.
        self.pip_vulns: dict[tuple[str, str], list[dict[str, Any]]] = {}
        # Pins pip-audit leaves out of its report without a skip_reason.
        self.pip_drops: set[str] = set()
        self.audited_files: list[str] = []
        self.ignore_text = ""
        self.plugin_package: dict[str, Any] = {"name": "flightdeck-plugin", "private": True}

    def fake_run(self, cmd: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
        if cmd[0] == "npm":
            if cwd.name == "dashboard":
                self.assertNotIn("--omit=dev", cmd)
                report = self.dashboard_all
            else:
                report = self.plugin_prod if "--omit=dev" in cmd else self.plugin_all
            return completed(json.dumps(report), code=1)
        if cmd[:2] == ["uv", "export"]:
            self.assertIn("--locked", cmd)
            return completed(self.runtime_export if "--no-dev" in cmd else self.full_export)
        if cmd[0] == "uvx":
            self.assertEqual(cmd[1:3], ["--exclude-newer", "14 days"])
            text = Path(cmd[cmd.index("--requirement") + 1]).read_text()
            self.audited_files.append(text)
            deps = []
            for line in text.splitlines():
                name, _, version = line.partition("==")
                if line in self.pip_drops:
                    continue
                deps.append(
                    {
                        "name": name,
                        "version": version,
                        "vulns": self.pip_vulns.get((name, version), []),
                    }
                )
            return completed(json.dumps({"dependencies": deps, "fixes": []}), code=1)
        raise AssertionError(f"unexpected command {cmd}")

    def run_main(self) -> tuple[int, str]:
        root = Path(tempfile.mkdtemp())
        (root / "dashboard").mkdir()
        (root / "dashboard" / "package-lock.json").write_text("{}")
        (root / "plugin").mkdir()
        (root / "plugin" / "package.json").write_text(json.dumps(self.plugin_package))
        if self.plugin_lock:
            (root / "plugin" / "package-lock.json").write_text("{}")
        ignore_file = root / "vuln-ignore.toml"
        ignore_file.write_text(self.ignore_text)
        out = io.StringIO()
        with (
            mock.patch.object(vuln_scan, "ROOT", root),
            mock.patch.object(vuln_scan, "IGNORE_FILE", ignore_file),
            mock.patch.object(vuln_scan, "_run", side_effect=self.fake_run),
            mock.patch.dict("os.environ", {"GITHUB_ACTIONS": "true"}),
            redirect_stdout(out),
            redirect_stderr(out),
        ):
            code = vuln_scan.main(today=TODAY)
        return code, out.getvalue()

    def test_clean_scan_passes(self) -> None:
        code, out = self.run_main()
        self.assertEqual(code, 0, out)
        self.assertIn("no dependencies declared", out)

    def test_dashboard_high_and_critical_fail_dev_included(self) -> None:
        # The dashboard is audited once over every dependency, so a dev
        # dependency's high advisory fails just like a production one.
        for adv in (HIGH, CRITICAL):
            self.dashboard_all = npm_report(adv)
            code, out = self.run_main()
            self.assertEqual(code, 1, out)
            self.assertIn(
                f"FAIL: npm dashboard all dependencies, high and critical: {adv['name']}", out
            )
            self.assertIn("::error title=Vulnerable dependency::", out)

    def test_dashboard_moderate_is_report_only(self) -> None:
        self.dashboard_all = npm_report(MODERATE)
        code, out = self.run_main()
        self.assertEqual(code, 0, out)
        self.assertIn(MODERATE["ghsa"], out.split("npm dashboard, other advisories")[1])

    def test_plugin_gates_production_only(self) -> None:
        self.plugin_lock = True
        self.plugin_package["devDependencies"] = {"lodash": "4.17.20"}
        self.plugin_all = npm_report(HIGH)
        code, out = self.run_main()
        self.assertEqual(code, 0, out)
        self.assertIn(HIGH["ghsa"], out.split("npm plugin, other advisories")[1])
        self.plugin_prod = npm_report(HIGH)
        code, out = self.run_main()
        self.assertEqual(code, 1, out)

    def test_ignored_advisory_passes_with_reason(self) -> None:
        self.dashboard_all = npm_report(HIGH)
        self.ignore_text = ignore_toml(HIGH["ghsa"], "lodash")
        code, out = self.run_main()
        self.assertEqual(code, 0, out)
        self.assertIn("reason: no fixed release", out)

    def test_expired_ignore_entry_fails(self) -> None:
        self.dashboard_all = npm_report(HIGH)
        self.ignore_text = ignore_toml(HIGH["ghsa"], "lodash", expires="2026-11-01")
        code, out = self.run_main()
        self.assertEqual(code, 1, out)
        self.assertIn("expired on 2026-11-01", out)
        self.assertIn("::error title=Expired ignore entry::", out)

    def test_entry_expiring_today_still_holds(self) -> None:
        self.dashboard_all = npm_report(HIGH)
        self.ignore_text = ignore_toml(HIGH["ghsa"], "lodash", expires=TODAY.isoformat())
        code, out = self.run_main()
        self.assertEqual(code, 0, out)

    def test_stale_ignore_entry_is_annotated_not_failed(self) -> None:
        self.ignore_text = ignore_toml("GHSA-gone", "x")
        code, out = self.run_main()
        self.assertEqual(code, 0, out)
        self.assertIn(
            "::warning title=Stale ignore entry::ignore entry GHSA-gone (x) matched no finding",
            out,
        )

    def test_plugin_dependencies_without_lockfile_fail(self) -> None:
        self.plugin_package["dependencies"] = {"left-pad": "^1.0.0"}
        code, out = self.run_main()
        self.assertEqual(code, 1, out)
        self.assertIn("plugin/package.json declares dependencies", out)

    def test_any_sensor_runtime_advisory_fails(self) -> None:
        self.pip_vulns[("pydantic", "2.14.0")] = [PYDANTIC_VULN]
        code, out = self.run_main()
        self.assertEqual(code, 1, out)
        self.assertIn("FAIL: pip sensor runtime: pydantic@2.14.0 PYSEC-2024-1", out)

    def test_marker_gated_runtime_pin_is_audited(self) -> None:
        # pip-audit would drop this pin on a non-Windows interpreter; the
        # scanner strips the marker so the pin is audited anyway.
        self.runtime_export += "jinja2==3.1.2 ; sys_platform == 'win32'\n"
        self.pip_vulns[("jinja2", "3.1.2")] = [JINJA_VULN]
        code, out = self.run_main()
        self.assertEqual(code, 1, out)
        self.assertIn("FAIL: pip sensor runtime: jinja2@3.1.2 PYSEC-2026-1473", out)
        self.assertTrue(all(";" not in text for text in self.audited_files))

    def test_runtime_pin_missing_from_report_fails(self) -> None:
        self.pip_drops = {"pydantic==2.14.0"}
        code, out = self.run_main()
        self.assertEqual(code, 1, out)
        self.assertIn("FAIL: pip sensor runtime: not audited: pydantic==2.14.0", out)

    def test_full_set_gap_is_listed_not_failed(self) -> None:
        self.full_export += "pywin32==311 ; sys_platform == 'win32'\n"
        self.pip_drops = {"pywin32==311"}
        code, out = self.run_main()
        self.assertEqual(code, 0, out)
        self.assertIn("not audited: pywin32==311", out.split("pip sensor extras and dev")[1])

    def test_duplicate_pins_are_audited_in_separate_files(self) -> None:
        self.full_export += (
            "deprecated==1.3.1 ; python_full_version < '3.12'\n"
            "deprecated==3.0.0 ; python_full_version >= '3.12'\n"
        )
        self.pip_vulns[("deprecated", "1.3.1")] = [JINJA_VULN]
        code, out = self.run_main()
        self.assertEqual(code, 0, out)
        self.assertIn("deprecated@1.3.1 PYSEC-2026-1473", out)
        for text in self.audited_files:
            self.assertLessEqual(text.count("deprecated=="), 1)

    def test_unaudited_sensor_runtime_package_fails(self) -> None:
        self.runtime_export += "local-pkg @ file:///tmp/local-pkg\n"
        code, out = self.run_main()
        self.assertEqual(code, 1, out)
        self.assertIn("not audited: local-pkg @ file:///tmp/local-pkg", out)

    def test_sensor_extras_advisory_is_report_only(self) -> None:
        self.full_export += "pillow==12.3.0\n"
        self.pip_vulns[("pillow", "12.3.0")] = [JINJA_VULN]
        code, out = self.run_main()
        self.assertEqual(code, 0, out)
        self.assertIn("pillow@12.3.0", out.split("pip sensor extras and dev")[1])

    def test_expiry_beyond_the_cap_fails(self) -> None:
        self.dashboard_all = npm_report(HIGH)
        too_far = TODAY + datetime.timedelta(days=vuln_scan.MAX_IGNORE_DAYS + 1)
        self.ignore_text = ignore_toml(HIGH["ghsa"], "lodash", expires=too_far.isoformat())
        code, out = self.run_main()
        self.assertEqual(code, 1, out)
        self.assertIn(f"more than {vuln_scan.MAX_IGNORE_DAYS} days out", out)
        at_cap = TODAY + datetime.timedelta(days=vuln_scan.MAX_IGNORE_DAYS)
        self.ignore_text = ignore_toml(HIGH["ghsa"], "lodash", expires=at_cap.isoformat())
        code, out = self.run_main()
        self.assertEqual(code, 0, out)

    def test_empty_runtime_export_returns_two(self) -> None:
        # uv export exits 0 but lists no pins: nothing would be audited.
        self.runtime_export = "# This file was autogenerated by uv\n"
        code, out = self.run_main()
